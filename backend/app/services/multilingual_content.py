def detect_domain(topic: str) -> Optional[str]:
    """Detects primary domain from topic string."""
    t = topic.lower()
    if any(k in t for k in ["corona", "covid", "virus", "pandemic", "quarantine", "rt-pcr", "mask"]):
        return "corona"
    if any(k in t for k in ["dengue", "malaria", "mosquito", "chikungunya"]):
        return "dengue"
    if any(k in t for k in ["flood", "cyclone", "rain", "storm", "inundation", "tsunami"]):
        return "flood"
    if any(k in t for k in ["heat", "heatwave", "summer", "sunstroke", "temperature"]):
        return "heatwave"
    if any(k in t for k in ["vaccin", "immuniz", "polio", "booster"]):
        return "vaccine"
    if any(k in t for k in ["education", "scholarship", "exam", "admission", "school", "college", "student"]):
        return "education"
    if any(k in t for k in ["water", "electricity", "power", "pipeline", "blackout", "load shedding"]):
        return "water"
    if any(k in t for k in ["traffic", "transit", "metro", "road", "diversion", "transport"]):
        return "traffic"
    if any(k in t for k in ["cyber", "fraud", "scam", "phishing", "otp", "online safety"]):
        return "cyber"
    return None


