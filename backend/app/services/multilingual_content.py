def get_multilingual_message(
    topic: str,
    language: str = "English",
    guidance: str = "",
    tone: str = "Formal",
    channel: str = "Email",
    max_chars: int = 600
) -> str:
    """
    Main entry point for generating content in ANY specified language.
    """
    lang_code = LANG_KEY_MAP.get(language.lower().strip(), "en")
    domain = detect_domain(topic)

    if domain and domain in DOMAIN_MESSAGES:
        lang_dict = DOMAIN_MESSAGES[domain]
        if lang_code in lang_dict:
            msg = lang_dict[lang_code]
            if len(msg) > max_chars:
                msg = msg[:max_chars - 3].rstrip() + "..."
            return msg

    # Fallback to dynamic multilingual synthesis
    return generate_dynamic_multilingual(
        topic=topic,
        guidance=guidance,
        tone=tone,
        channel=channel,
        lang_code=lang_code,
        max_chars=max_chars
    )
